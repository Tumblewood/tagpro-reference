"""
Picks which award icon to show for an award placement or championship. The icons
themselves are generated by scripts/generate_award_icons.py into
static/reference/awards/.

AwardType.icon holds the base name of an award's icon, like "medal_mvb" or
"ribbon_heart". Medals get a strap color from the league and a metal from the
placement; ribbons only depend on the placement.
"""

AWARD_ICON_DIR = "awards"
GENERIC_TROPHY_ICON = "awards/trophy_generic.svg"

# Medal strap color for each league. Leagues not listed get a white strap.
LEAGUE_STRAP_COLORS = {
    "MLTP": "blue",
    "ELTP": "blue",
    "OLTP": "blue",
    "mLTP": "red",
    "eLTP": "red",
    "oLTP": "red",
    "NLTP": "orange",
    "ENLTP": "orange",
    "NLTP B": "green",
}
DEFAULT_STRAP_COLOR = "white"

ICON_PLACEMENTS = {1, 2, 3}

# All-Star placements only order the selections, so every All-Star gets the 1st place icon.
UNRANKED_ICONS = {"medal_all_star", "medal_all_star_o", "medal_all_star_d"}


def award_icon_path(icon, league_abbr, placement):
    """
    Returns the static path of the icon for placing in an award, or None if the
    award has no icon or the placement doesn't get one.
    """
    if not icon:
        return None
    if icon in UNRANKED_ICONS:
        placement = 1
    if placement not in ICON_PLACEMENTS:
        return None
    if icon.startswith("medal_"):
        strap = LEAGUE_STRAP_COLORS.get(league_abbr, DEFAULT_STRAP_COLOR)
        return f"{AWARD_ICON_DIR}/{icon}_{strap}_{placement}.svg"
    return f"{AWARD_ICON_DIR}/{icon}_{placement}.svg"


def trophy_icon_path(league):
    """Returns the static path of a league's championship trophy."""
    return league.trophy_icon or GENERIC_TROPHY_ICON
